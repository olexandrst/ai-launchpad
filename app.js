// Toggle favorite
function toggleFavorite(tileId) {
    const index = favorites.indexOf(tileId);
    if (index > -1) {
        favorites.splice(index, 1);
    } else {
        favorites.push(tileId);
    }
    localStorage.setItem('favorites', JSON.stringify(favorites));
    return favorites.includes(tileId);
}

